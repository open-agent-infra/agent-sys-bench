#!/bin/bash
# setup.sh — Configure global environment parameters for AgentSysBench.
#
# Usage:
#   bash scripts/setup.sh
#   PIP_INDEX_URL=https://mirrors.aliyun.com/pypi/simple/ bash scripts/setup.sh
#
# This script writes a .env file at the repo root with shared parameters
# used by Docker builds and compose deployments. Run it once after cloning.

set -e

AGSBENCH_HOME="$(cd "$(dirname "$0")/.." && pwd)"

# Build-time mirrors (override via environment for China or internal mirrors)
PIP_INDEX_URL="${PIP_INDEX_URL:-https://mirrors.aliyun.com/pypi/simple/}"
NPM_REGISTRY="${NPM_REGISTRY:-https://registry.npmmirror.com}"
# Prefix for github.com downloads in build scripts; set GITHUB_PROXY= (empty) to go direct
GITHUB_PROXY="${GITHUB_PROXY-https://ghfast.top/}"

cat > "${AGSBENCH_HOME}/.env" << EOF
# Generated by scripts/setup.sh — $(date -Iseconds)
# Re-run to update. This file is gitignored.

# Repo root (used by compose files for volume mounts)
AGSBENCH_HOME=${AGSBENCH_HOME}

# Build-time package mirrors (passed as --build-arg to docker build)
PIP_INDEX_URL=${PIP_INDEX_URL}
NPM_REGISTRY=${NPM_REGISTRY}
GITHUB_PROXY=${GITHUB_PROXY}
EOF

echo ""
echo "  AGSBENCH_HOME   = ${AGSBENCH_HOME}"
echo "  PIP_INDEX_URL  = ${PIP_INDEX_URL}"
echo "  NPM_REGISTRY   = ${NPM_REGISTRY}"
echo "  GITHUB_PROXY   = ${GITHUB_PROXY:-(direct)}"
echo ""
echo "Next:"
echo "  bash scripts/configure-api.sh    # configure LLM/embedding/search APIs"
echo "  cd agents/<name> && bash scripts/build_image.sh   # build agent image"
