#######################################################
#    client invoking        #      service serving
#  ---------------------------------------------------
#  v developer-function     #     developer-function ^
#  v   context-layer        #       monitor-layer    ^
#  v intermediate-layer     #     intermediate-layer ^
#  v   monitor-layer        #       context-layer    ^
#  v    file-layer          #        file-layer      ^
#  v   engine-layer         #       engine-layer     ^
#  > > > > > > > > > > > > > > > > > > > > > > > > > >
#     requests/rpc   ===transport===>  fastapi/rpc
#######################################################
#  In client invoking case, the execution of developer-function will be replaced with remote call wrapped by necessary
#  layers. In service serving case, the execution of developer-function will be invoked by serving thread, where it is
#  invoked after the execution of necessary layers.
#
#  This is not a symmetrical structure as normal network layers, because the execution of monitor-layer relies on the
#  thread-local context object generated by context-layer during runtime. Therefore, the context-layer must be invoked
#  before monitor-layer.
#
#  In python, the wrapped function will be executed during wrapper execution, which means the wrapped one shall be
#  generated first.
#
#  When rewriting client, the developer-function will be used to generate the engine-layer first, and rewriting will
#  be performed in a bottom-up order. The final step is replacing developer-function with rewritten function.
#  When rewriting service, rewriting will be performed in a top-down order.
#

from typing import Callable, Optional

from ..config import FastServiceConfig
from ..engine import IFastServiceEngine
from ..monitor import FastServiceMonitorManager
from ..intermediate import IntermediateManager
from ..description import FunctionDescriptor, FunctionName

from .layer import ExecutionLayer
from .context_layer import ContextLayer
from .monitor_layer import MonitorLayer
from .file_layer import FileLayer
from .engine_layer import EngineLayer
from .intermediate_layer import IntermediateLayer


class LayerBuilder:

    top_layer: Optional[ExecutionLayer | None]
    current_layer: Optional[ExecutionLayer | None]

    def __init__(self):
        self.top_layer = None
        self.current_layer = None

    def build_layer(self, layer: ExecutionLayer) -> "LayerBuilder":
        if layer is None:
            return self

        if self.top_layer is None:
            self.top_layer = layer
            self.current_layer = layer
            return self

        self.current_layer.set_next_layer(layer)
        self.current_layer = layer
        return self


class FastServiceRewriter:

    config: FastServiceConfig
    engine: IFastServiceEngine
    monitor_manager: FastServiceMonitorManager
    intermediate_manager: IntermediateManager

    local_service: list
    remote_service: list

    # in invoking order, the outside layer will be invoked before the inside layer
    client_chain: ExecutionLayer
    service_chain: ExecutionLayer
    local_function_chain: ExecutionLayer

    def __init__(
        self,
        config: FastServiceConfig,
        engine: IFastServiceEngine,
        monitor_manager: FastServiceMonitorManager,
        intermediate_manager: IntermediateManager,
    ):
        self.config = config
        self.engine = engine
        self.monitor_manager = monitor_manager
        self.intermediate_manager = intermediate_manager

        self.local_service = []
        self.remote_service = []

        for single_service in self.config.service_dict.values():
            if (
                single_service.ip == self.config.ip
                and single_service.port == self.config.port
            ):
                self.local_service.append(
                    FunctionName(single_service.module_name, single_service.name)
                )
            else:
                self.remote_service.append(
                    FunctionName(single_service.module_name, single_service.name)
                )

        if len(self.local_service) > 0:
            service_layer_builder = LayerBuilder()
            service_layer_builder.build_layer(
                EngineLayer(self.engine, self.config.service_dict)
            ).build_layer(FileLayer()).build_layer(ContextLayer())
            if self.config.store_intermediate:
                service_layer_builder.build_layer(
                    IntermediateLayer(self.intermediate_manager)
                )
            if self.config.monitor:
                service_layer_builder.build_layer(MonitorLayer(self.monitor_manager))
            self.service_chain = service_layer_builder.top_layer

        if len(self.remote_service) > 0:
            client_layer_builder = LayerBuilder()
            client_layer_builder.build_layer(ContextLayer())
            if self.config.store_intermediate:
                client_layer_builder.build_layer(
                    IntermediateLayer(self.intermediate_manager)
                )
            if self.config.monitor:
                client_layer_builder.build_layer(MonitorLayer(self.monitor_manager))
            client_layer_builder.build_layer(FileLayer()).build_layer(
                EngineLayer(self.engine, self.config.service_dict)
            )
            self.client_chain = client_layer_builder.top_layer

        local_function_layer_builder = LayerBuilder()
        local_function_layer_builder.build_layer(ContextLayer())
        if self.config.store_intermediate:
            local_function_layer_builder.build_layer(
                IntermediateLayer(self.intermediate_manager)
            )
        if self.config.monitor:
            local_function_layer_builder.build_layer(MonitorLayer(self.monitor_manager))
        self.local_function_chain = local_function_layer_builder.top_layer

    def rewrite(self, function_descriptor: FunctionDescriptor) -> Callable:
        if function_descriptor.name in self.local_service:
            if function_descriptor.is_async:
                return self.service_chain.setup_async_service(
                    function_descriptor.f, function_descriptor
                )
            else:
                return self.service_chain.setup_service(
                    function_descriptor.f, function_descriptor
                )
        elif function_descriptor.name in self.remote_service:
            if function_descriptor.is_async:
                return self.client_chain.setup_async_client(
                    function_descriptor.f, function_descriptor
                )
            else:
                return self.client_chain.setup_client(
                    function_descriptor.f, function_descriptor
                )
        else:
            return self.local_function_chain.setup_local_function(
                function_descriptor.f, function_descriptor
            )
